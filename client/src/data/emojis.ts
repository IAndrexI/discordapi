const FREQUENT_STORAGE_KEY = 'protutech_frequent_emojis_v1';
const DEFAULT_FREQUENT = ['👍', '❤️', '😂', '🔥', '🚀', '👀', '🎉', '💯', '😭', '💀', '✨', '⚡'];

export function getFrequentEmojis(): string[] {
  if (typeof localStorage === 'undefined') return DEFAULT_FREQUENT;
  try {
    const raw = localStorage.getItem(FREQUENT_STORAGE_KEY);
    if (!raw) return DEFAULT_FREQUENT;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed.slice(0, 16);
    }
  } catch {
    // Ignore corrupt storage
  }
  return DEFAULT_FREQUENT;
}

export function recordEmojiUse(emoji: string): void {
  if (typeof localStorage === 'undefined' || !emoji) return;
  try {
    const current = getFrequentEmojis().filter((e) => e !== emoji);
    const next = [emoji, ...current].slice(0, 16);
    localStorage.setItem(FREQUENT_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // Ignore storage errors
  }
}

export function searchEmojis(query: string, limit = 64): EmojiItem[] {
  const q = query.trim().toLowerCase().replace(/^:/, '').replace(/:$/, '');
  if (!q) return ALL_EMOJIS.slice(0, limit);
  const matches: EmojiItem[] = [];
  for (const item of ALL_EMOJIS) {
    if (
      item.name.includes(q) ||
      item.keywords.some((k) => k.includes(q)) ||
      item.emoji === q
    ) {
      matches.push(item);
      if (matches.length >= limit) break;
    }
  }
  return matches;
}
